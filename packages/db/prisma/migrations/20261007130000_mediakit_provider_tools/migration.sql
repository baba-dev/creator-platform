CREATE TABLE `ProviderTool` (
  `id` VARCHAR(191) NOT NULL,
  `provider` ENUM('BYTEPLUS','NVIDIA','GROQ','GEMINI','CLOUDFLARE') NOT NULL,
  `providerToolId` VARCHAR(191) NOT NULL,
  `displayName` VARCHAR(191) NOT NULL,
  `description` TEXT NOT NULL,
  `category` VARCHAR(32) NOT NULL,
  `executionMode` ENUM('ASYNC','SYNC') NOT NULL,
  `pricingMetric` ENUM('REQUEST','INPUT_SECOND','OUTPUT_SECOND') NOT NULL,
  `capabilities` JSON NOT NULL,
  `enabled` BOOLEAN NOT NULL DEFAULT false,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `ProviderTool_provider_providerToolId_key`(`provider`, `providerToolId`),
  INDEX `ProviderTool_enabled_category_idx`(`enabled`, `category`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `ProviderToolPriceVersion` (
  `id` VARCHAR(191) NOT NULL,
  `providerToolId` VARCHAR(191) NOT NULL,
  `publicationKey` VARCHAR(36) NULL,
  `publicationHash` VARCHAR(64) NULL,
  `providerCostMicroUsd` BIGINT NOT NULL,
  `customerCredits` BIGINT NOT NULL,
  `fxBaisaNumerator` BIGINT NOT NULL,
  `fxBaisaDenominator` BIGINT NOT NULL,
  `targetMarginBps` INTEGER NOT NULL,
  `pricingMetric` ENUM('REQUEST','INPUT_SECOND','OUTPUT_SECOND') NOT NULL,
  `unitQuantity` INTEGER NOT NULL DEFAULT 1,
  `creditsPerBaisa` BIGINT NOT NULL DEFAULT 1,
  `providerCostBasisNote` VARCHAR(255) NULL,
  `effectiveFrom` DATETIME(3) NOT NULL,
  `effectiveTo` DATETIME(3) NULL,
  `createdById` VARCHAR(191) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `ProviderToolPriceVersion_publicationKey_key`(`publicationKey`),
  INDEX `ProviderToolPriceVersion_providerToolId_effectiveFrom_idx`(`providerToolId`, `effectiveFrom`),
  INDEX `ProviderToolPriceVersion_effectiveFrom_effectiveTo_idx`(`effectiveFrom`, `effectiveTo`),
  CONSTRAINT `ProviderToolPriceVersion_providerToolId_fkey` FOREIGN KEY (`providerToolId`) REFERENCES `ProviderTool`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProviderToolPriceVersion_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

