  CONSTRAINT `ProviderToolExecution_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProviderToolExecution_providerToolId_fkey` FOREIGN KEY (`providerToolId`) REFERENCES `ProviderTool`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ProviderToolExecution_priceVersionId_fkey` FOREIGN KEY (`priceVersionId`) REFERENCES `ProviderToolPriceVersion`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
